(function (global) {
    var TAU = Math.PI * 2;

    function draw(ctx, fields, rotation, size) {
        var c = size / 2;
        var r = c - 46;
        var slice = TAU / Math.max(1, fields.length);
        ctx.clearRect(0, 0, size, size);
        ctx.save();
        ctx.translate(c, c);
        ctx.rotate(rotation);
        ctx.beginPath();
        ctx.arc(0, 0, r + 16, 0, TAU);
        ctx.fillStyle = "#5c4a1e";
        ctx.fill();
        ctx.beginPath();
        ctx.arc(0, 0, r + 8, 0, TAU);
        ctx.fillStyle = "#f1c40f";
        ctx.fill();
        fields.forEach(function (task, i) {
            var a0 = i * slice - Math.PI / 2;
            ctx.beginPath();
            ctx.moveTo(0, 0);
            ctx.arc(0, 0, r, a0, a0 + slice);
            ctx.closePath();
            var glow = ctx.createRadialGradient(0, 0, r * 0.15, 0, 0, r);
            glow.addColorStop(0, task.bust ? "#2a2a2a" : "#fff6d0");
            glow.addColorStop(0.45, task.color || "#f1c40f");
            glow.addColorStop(1, task.bust ? "#050505" : (task.color || "#f1c40f"));
            ctx.fillStyle = glow;
            ctx.fill();
            ctx.strokeStyle = "#f6e7a8";
            ctx.lineWidth = 4;
            ctx.stroke();
            ctx.beginPath();
            ctx.arc(Math.cos(a0) * (r - 2), Math.sin(a0) * (r - 2), 8, 0, TAU);
            ctx.fillStyle = "#fff4c2";
            ctx.fill();
            ctx.strokeStyle = "#8a6a12";
            ctx.lineWidth = 2;
            ctx.stroke();
            ctx.save();
            ctx.rotate(a0 + slice / 2);
            ctx.translate(r * 0.8, 0);
            ctx.rotate(Math.PI / 2);
            ctx.fillStyle = task.ink || "#fff";
            ctx.font = "800 46px sans-serif";
            ctx.textAlign = "center";
            ctx.textBaseline = "middle";
            ctx.fillText(String(task.n || ""), 0, 0);
            ctx.restore();
        });
        ctx.beginPath();
        ctx.arc(0, 0, r * 0.2, 0, TAU);
        var hub = ctx.createRadialGradient(0, 0, 4, 0, 0, r * 0.2);
        hub.addColorStop(0, "#fff4c2");
        hub.addColorStop(0.55, "#f1c40f");
        hub.addColorStop(1, "#6e5410");
        ctx.fillStyle = hub;
        ctx.fill();
        ctx.lineWidth = 6;
        ctx.strokeStyle = "#1a1404";
        ctx.stroke();
        ctx.restore();
        var tip = c - r + 22;
        var base = c - r - 36;
        ctx.beginPath();
        ctx.moveTo(c, tip);
        ctx.lineTo(c - 30, base);
        ctx.lineTo(c + 30, base);
        ctx.closePath();
        ctx.fillStyle = "#f1c40f";
        ctx.fill();
        ctx.lineWidth = 4;
        ctx.strokeStyle = "#1a1404";
        ctx.stroke();
    }

    global.KoloWheel = { draw: draw, TAU: TAU };
})(window);
